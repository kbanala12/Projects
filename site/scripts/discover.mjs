// Scans the repository for project folders and reconciles them with
// data/projects.json. Existing curated entries are preserved; new folders are
// added as stubs flagged needsReview, and missing files are reported.
import fs from 'node:fs';
import path from 'node:path';
import { REPO_DIR, loadProjects, saveProjects, slugify, repoPath, log } from './lib.mjs';

const IGNORE = new Set(['site', '.git', '.github', 'node_modules', 'docs']);
const db = loadProjects();
const byFolder = new Map(db.projects.map((p) => [p.folder, p]));
const problems = [];

const folders = fs
  .readdirSync(REPO_DIR, { withFileTypes: true })
  .filter((d) => d.isDirectory() && !IGNORE.has(d.name) && !d.name.startsWith('.'))
  .map((d) => d.name)
  .sort();

for (const folder of folders) {
  if (byFolder.has(folder)) continue;
  const readmePath = path.join(REPO_DIR, folder, 'README.md');
  let title = folder;
  if (fs.existsSync(readmePath)) {
    const h1 = fs.readFileSync(readmePath, 'utf8').match(/^#\s+(.+)$/m);
    if (h1) title = h1[1].trim();
  }
  const files = walk(path.join(REPO_DIR, folder)).map((f) => path.relative(REPO_DIR, f));
  db.projects.push({
    slug: slugify(title),
    title,
    shortTitle: title,
    pitch: 'TODO: one-line pitch',
    domain: 'TODO',
    tags: [],
    tools: [],
    languages: [],
    year: new Date().getFullYear(),
    featured: false,
    needsReview: true,
    folder,
    readme: fs.existsSync(readmePath) ? `${folder}/README.md` : null,
    data: { name: 'TODO', source: 'TODO', url: '', records: '', files },
    story: { question: 'TODO', method: 'TODO', finding: 'TODO' },
    metrics: [],
    signature: null,
    visuals: extractReadmeImages(readmePath),
    links: [],
    inferred: ['Stub generated by scripts/discover.mjs; fill in every TODO.'],
  });
  log(`added stub for new folder: ${folder}`);
}

for (const p of db.projects) {
  if (!fs.existsSync(repoPath(p.folder))) problems.push(`${p.slug}: folder missing (${p.folder})`);
  for (const f of p.data?.files || []) {
    if (!fs.existsSync(repoPath(f))) problems.push(`${p.slug}: data file missing (${f})`);
  }
  for (const key of ['slug', 'title', 'pitch', 'domain', 'tools', 'story']) {
    if (!p[key]) problems.push(`${p.slug}: missing ${key}`);
  }
  if (!p.visuals?.length) problems.push(`${p.slug}: no visuals`);
}

const slugs = new Set();
for (const p of db.projects) {
  if (slugs.has(p.slug)) problems.push(`duplicate slug ${p.slug}`);
  slugs.add(p.slug);
}

saveProjects(db);

console.log('\nProject inventory');
console.table(
  db.projects.map((p) => ({
    slug: p.slug,
    domain: p.domain,
    year: p.year,
    tools: p.tools.join(', '),
    visuals: p.visuals?.length ?? 0,
    review: p.needsReview ? 'yes' : '',
  }))
);
if (problems.length) {
  console.log('\nProblems:');
  for (const m of problems) console.log(' -', m);
  process.exitCode = 1;
} else {
  log('inventory ok');
}

function walk(dir) {
  const out = [];
  for (const d of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, d.name);
    if (d.isDirectory()) out.push(...walk(full));
    else out.push(full);
  }
  return out;
}

function extractReadmeImages(readmePath) {
  if (!fs.existsSync(readmePath)) return [];
  const text = fs.readFileSync(readmePath, 'utf8');
  const ids = [...text.matchAll(/github\.com\/user-attachments\/assets\/([a-f0-9-]+)/g)].map((m) => m[1]);
  return [...new Set(ids)].map((id, i) => ({
    id,
    role: i === 0 ? 'hero' : 'figure',
    alt: 'TODO: describe this figure',
    caption: '',
  }));
}
